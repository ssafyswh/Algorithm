import sys

tetris = [
    ((0, 0), (0, 1), (0, 2), (0, 3)),   # I 가로
    ((0, 0), (1, 0), (2, 0), (3, 0)),   # I 세로
    ((0, 0), (1, 0), (0, 1), (1, 1)),   # O
    ((0, 0), (1, 0), (2, 0), (2, 1)),   # J / L
    ((0, 0), (1, 0), (2, 0), (2, -1)),
    ((0, 0), (-1, 0), (-2, 0), (-2, 1)),
    ((0, 0), (-1, 0), (-2, 0), (-2, -1)),
    ((0, 0), (1, 0), (1, 1), (1, 2)),
    ((0, 0), (1, 0), (1, -1), (1, -2)),
    ((0, 0), (-1, 0), (-1, 1), (-1, 2)),
    ((0, 0), (-1, 0), (-1, -1), (-1, -2)),
    ((0, 0), (1, 0), (1, 1), (2, 1)),   # Z / S
    ((0, 0), (1, 0), (1, -1), (2, -1)),
    ((0, 0), (0, 1), (-1, 1), (-1, 2)),
    ((0, 0), (0, 1), (1, 1), (1, 2)),
    ((0, 0), (0, 1), (0, 2), (1, 1)),   # T
    ((0, 0), (1, 0), (2, 0), (1, 1)),
    ((0, 0), (0, 1), (0, 2), (-1, 1)),
    ((0, 0), (1, 0), (2, 0), (1, -1)),
]

N, M = map(int, input().split())
paper = [list(map(int, sys.stdin.readline().split())) for _ in range(N)]
result = 0
for y in range(N):
    for x in range(M):
        for mino in tetris:
            temp_sum = 0
            for i in range(4):
                dy, dx = y + mino[i][0], x + mino[i][1]
                if not(0 <= dy < N and 0 <= dx < M):
                    break
                temp_sum += paper[dy][dx]
            else:
                result = max(result, temp_sum)
print(result)